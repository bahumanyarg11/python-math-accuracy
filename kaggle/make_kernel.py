"""Create a private Kaggle script kernel that unpacks this project and runs a
shell command.  usage: make_kernel.py <slug> "<command>" [gpu]"""
import sys, os, io, tarfile, base64, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
slug, cmd = sys.argv[1], sys.argv[2]
gpu = len(sys.argv) > 3 and sys.argv[3] == "gpu"
with_results = sys.argv[4] if len(sys.argv) > 4 else None   # include results/*/<tag>
buf = io.BytesIO()
with tarfile.open(fileobj=buf, mode="w:gz") as t:
    for d in ["harness", "gate", "ext/core-math", "drivers", "data", "kaggle/setup_cpu.sh", "kaggle/setup_gpu.sh"]:
        p = os.path.join(ROOT, d)
        if os.path.exists(p):
            t.add(p, arcname=d, filter=lambda ti: None if ti.name.endswith((".so", ".dylib", ".o", ".json.tmp")) or "/openlibm-0.8.7" in ti.name or "/math_accuracy" in ti.name or "__pycache__" in ti.name or "/.git" in ti.name else ti)
    if with_results:
        import glob
        for p in glob.glob(os.path.join(ROOT, "results", "*", with_results)):
            t.add(p, arcname=os.path.relpath(p, ROOT))
b64 = base64.b64encode(buf.getvalue()).decode()
run = f'''# generated by kaggle/make_kernel.py
import base64, io, tarfile, subprocess, os, sys
W = "/kaggle/working/pyacc"
os.makedirs(W, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode("{b64}")), mode="r:gz").extractall(W)
subprocess.run("(sudo -n true 2>/dev/null && S=sudo || S=''; $S apt-get -qq update; $S apt-get -qq install -y libmpfr-dev libgmp-dev) >/dev/null 2>&1", shell=True)
cmd = {cmd!r}
with open("/kaggle/working/log.txt", "w") as log:
    p = subprocess.Popen(cmd, shell=True, cwd=W, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        sys.stdout.write(line); log.write(line); log.flush()
    p.wait()
subprocess.run("cd /kaggle/working && tar czf results.tgz -C pyacc $(cd pyacc && ls -d results gate/*.json 2>/dev/null)", shell=True)
'''
d = os.path.join(ROOT, "kaggle", slug)
os.makedirs(d, exist_ok=True)
open(os.path.join(d, "run.py"), "w").write(run)
json.dump({"id": f"{os.environ.get('KAGGLE_USERNAME', 'your-kaggle-username')}/{slug}", "title": slug, "code_file": "run.py", "language": "python",
           "kernel_type": "script", "is_private": True, "enable_gpu": gpu, "enable_tpu": False,
           "enable_internet": True, "dataset_sources": [], "competition_sources": [],
           "kernel_sources": []}, open(os.path.join(d, "kernel-metadata.json"), "w"), indent=1)
print(d, len(run) // 1024, "KiB")
